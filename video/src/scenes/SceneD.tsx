import React from "react";
import { Sequence, Video, staticFile } from "remotion";

// Scene D [281,371) per SPEC §5 D + docs/pv-art-direction.md v13:
// PROOF mode — ONE large curated viewport showing a single decisive
// before->after from real footage. The dumped "PV ops" comp is hidden
// (masterPatch D_HIDDEN) and this scene authors the whole layout:
//
//   Left column : authored copy 「After Effectsで、／そのまま動かせる。」
//                 (SPEC §4 D) + ONE line of explanation.
//   Right stage : a single footage viewport — ae-decompose-auto.mp4,
//                 scripted AE capture of a real Restro Decompose run:
//                 before text -> trigger -> 13 stroke layers materialize
//                 -> held result. No panels, dialogs, or internal labels.
//
// Footage arc (verified by full-decode frame audit, see
// verification/wu-d-r34/): source is 1920x1080 screen capture; the comp
// canvas (checkerboard + "Restro" + red decomposed stroke pieces with
// path handles) sits at source x~532-1073, y~112-587 — identical
// viewer geometry across all three recordings.
//
//   clip A (src f588-627): "Restro" with red stroke pieces in position
//     1; the f622 jump shifts every stroke piece up-right inside the
//     clip — strokes visibly MOVE on their own = editability proof.
//   clip B (src f640-689): jump cut to the held state, then the f665
//     jump shifts the pieces again — a second in-clip move, holding
//     the final arrangement ~1s into the D tail.
//
// This is the decisive operation->result the footage actually contains:
// the decomposed stroke shapes are real, independent, movable objects —
// not a dialog, not a script log, not an annotation strip. Re-record
// was evaluated and is unnecessary: all three recordings were audited
// frame-accurately and this is the most legible proof arc.

const T0 = 281 / 24;
const T1 = 371 / 24;
const FPS = 24;

type Roi = { x: number; y: number; w: number; h: number };
type Clip = {
  srcStart: number; // seconds into the source at clip start
  dur: number; // window frames this clip occupies
};

const SRC_W = 1920;
const SRC_H = 1080;

// Tight artwork crop (r35): a full-decode pixel audit of the source
// (verification/wu-d-r34/src/f*.rgb) shows the decomposed stroke pieces +
// path handles occupy only ~x695-1065, y210-360 of the 1920x1080 frame —
// the rest of the comp canvas is empty checkerboard plus a near-invisible
// white "Restro" (white-on-light, ~zero contrast). The r34 ROI included
// ~70% empty canvas, so the proof subject rendered tiny. This ROI hugs
// the stroke cluster with ~40-90px checkerboard margin on every side and
// stays fully inside the comp-canvas viewer (no dark AE UI chrome).
// r36: replaced screen-capture clips with ae-decompose-auto.mp4 — footage
// generated by the scripted AE pipeline (tools/capture/wu-d-capture2.jsx):
// a real Restro Decompose run on a live text layer produces 13 STROKE_*
// shape layers, then authored keyframes cut the "before" text twin and
// stagger the strokes materializing into the kanji. Single unbroken take
// srcStart 1.30s: text hold -> trigger -> stroke materialization -> result
// hold. This is the decisive operation->result the D beat needs.
// r36b: measured ink bounds in ae-decompose-auto.mp4 (PIL scan of the
// held frame): glyph occupies x400-878, y0-432 of the 1280x720 comp — the
// text anchor places the kanji high. ROI hugs that content box.
const ROI: Roi = { x: 370, y: 0, w: 560, h: 470 };

const CLIPS: Clip[] = [
  // One continuous take: 0.3s of "before" text, the cut, ~1.3s of strokes
  // materializing, then the held decomposed result for the rest of D.
  { srcStart: 1.30, dur: 90 },
];

// No jump accents: the new footage moves continuously on its own.
const JUMP_FRAMES: number[] = [];
const punch = (frame: number, jump: number) => {
  const x = (frame - jump) / 8; // 8-frame pulse
  return x > 0 && x < 1 ? Math.sin(Math.PI * x) : 0;
};

const WIN = {
  file: "ae-decompose-auto.mp4",
  roi: ROI,
  // r35: viewport now spans the full right stage width (x480-1080) and
  // uses the tight ROI — stroke scale goes 0.93 -> ~1.45x source, so the
  // decomposed pieces are actually identifiable as letter fragments.
  x: 480,
  y: 90,
  w: 600,
  h: 560, // 600/560 = 1.071 ~ roi aspect 560/520 = 1.077
  fIn: 281,
  // fOut removed: the window holds to the D->E hard cut (see SceneD).
  // New footage is light BG + colored strokes — the old heavy grade was
  // tuned for dark checkerboard capture and would crush this material.
  filter: "contrast(1.03) saturate(1.05)",
};

const ramp = (t: number, a: number, b: number) =>
  Math.min(1, Math.max(0, (t - a) / (b - a)));
const smooth = (x: number) => x * x * (3 - 2 * x);

// Uniform-scale cover of `roi` inside w x h, then center the roi. Returns
// the inner video box (source pixel size * scale) and its offset.
function coverBox(roi: Roi, w: number, h: number) {
  const s = Math.max(w / roi.w, h / roi.h);
  return {
    scale: s,
    width: SRC_W * s,
    height: SRC_H * s,
    left: w / 2 - (roi.x + roi.w / 2) * s,
    top: h / 2 - (roi.y + roi.h / 2) * s,
  };
}

export const SceneD: React.FC<{ t: number }> = ({ t }) => {
  if (t < T0 || t >= T1) return null;

  const tIn = WIN.fIn / FPS;
  // No fade-out: art direction prefers hard cuts, and r34 review failed
  // the tail — a fading viewport lost the proof legibility exactly at the
  // scene's strongest result frame. The window holds full opacity to the
  // D->E cut (f370 -> f371), matching the scene's hard-cut grammar.
  const pin = smooth(ramp(t, tIn, tIn + 0.22));
  const opacity = pin;

  // Left column copy (SPEC §4 D). Fades in with the scene and HOLDS to the
  // last D frame — r35 review failed the r34 tail fade as premature
  // deletion. SceneD returns null for t >= T1, so the f370->f371 hard cut
  // needs no opacity fade (no ghost is possible across a scene boundary).
  const copyIn = smooth(ramp(t, T0, T0 + 0.3));
  const copyOpacity = copyIn;

  const vb = coverBox(WIN.roi, WIN.w, WIN.h);

  return (
    <div style={{ position: "absolute", inset: 0, pointerEvents: "none" }}>
      {copyOpacity > 0 && (
        <div
          style={{
            position: "absolute",
            left: 44,
            // brand lockup (Restro/筆画復元) bottom edge is ~y550; keep a
            // clear gap — r25 failed on perceived collision at y596.
            top: 648,
            width: 400,
            opacity: copyOpacity,
            transform: `translateY(${(1 - copyIn) * 10}px)`,
            fontFamily: "'Noto Sans JP', 'Hiragino Sans', sans-serif",
            color: "#111",
          }}
        >
          <div style={{ fontSize: 40, fontWeight: 800, lineHeight: 1.3, letterSpacing: 0.5 }}>
            After Effectsで、
          </div>
          <div style={{ fontSize: 40, fontWeight: 800, lineHeight: 1.3, letterSpacing: 0.5 }}>
            そのまま動かせる。
          </div>
          <div style={{ marginTop: 14, fontSize: 20, fontWeight: 500, color: "#444", lineHeight: 1.5 }}>
            分解した筆画がレイヤーとして動く
          </div>
        </div>
      )}

      {opacity > 0 && (
        <div
          style={{
            position: "absolute",
            left: WIN.x,
            top: WIN.y,
            width: WIN.w,
            height: WIN.h,
            opacity,
            transform: `translateY(${(1 - pin) * 12}px) scale(${0.985 + 0.015 * pin})`,
            transformOrigin: "50% 50%",
          }}
        >
          {/* single curated viewport: thin-edged matte, no caption strip,
              no PiP insets, no internal labels (art-direction v13 D) */}
          <div
            style={{
              position: "absolute",
              inset: 0,
              overflow: "hidden",
              border: "1px solid rgba(15,15,15,0.5)",
              background: "#0c0c0c",
            }}
          >
            {CLIPS.map((clip, i) => {
              const from =
                WIN.fIn + CLIPS.slice(0, i).reduce((a, c) => a + c.dur, 0);
              return (
                <Sequence
                  key={i}
                  from={from}
                  durationInFrames={clip.dur}
                  layout="none"
                >
                  <div
                    style={{
                      position: "absolute",
                      left: vb.left,
                      top: vb.top,
                      width: vb.width,
                      height: vb.height,
                      filter: WIN.filter,
                      transform: `scale(${1 + 0.06 * punch(t * FPS, JUMP_FRAMES[i])})`,
                      transformOrigin: "50% 50%",
                    }}
                  >
                    <Video
                      src={staticFile(`assets/rec/${WIN.file}`)}
                      trimBefore={Math.round(clip.srcStart * FPS)}
                      muted
                      style={{ width: "100%", height: "100%", display: "block" }}
                    />
                  </div>
                </Sequence>
              );
            })}
          </div>
        </div>
      )}
    </div>
  );
};
