// Canonical Asset Registry & Registered-Space Reconstructor (Issue #32)
// Browser-safe (zero node:fs dependency) so both Node/Bun verification tools AND
// Remotion prototypes derive geometry and transforms from the exact same registry.

export interface AssetRegistration {
  comp: string;
  elementIndex: number;
  referenceSpace: string;
  /** Top-left offset (x0, y0) of tight asset frame in source space before padding. */
  sourceOrigin: [number, number];
  /** Padding inside the individual SVG viewBox (translate = [pad - x0, pad - y0]). */
  svgPad: number;
  /** Offset baked inside SVG root <g transform="translate(tx, ty)">. */
  svgTranslate: [number, number];
  /** Inverse placement back into source/reference space at the recorded rest time. */
  toReferenceTranslation: [number, number];
  poseTime: number;
}

export interface ManifestEntry {
  category: string;
  file: string;
  w: number;
  h: number;
  source: string;
  notes: string;
  registration?: AssetRegistration;
}

export interface ParsedSvgLayer {
  file: string;
  width: number;
  height: number;
  translate: [number, number];
  /** Any transform tokens on the root <g> after the leading translate(tx, ty) (e.g. kai-outline-merged matrix(1.3 ...)). */
  rootPostTransform?: string;
  /** Optional nested <g transform="..."> wrappers inside the root registration group. */
  innerGroupTransforms: string[];
  paths: Array<{
    d: string;
    matrixRaw?: string;
    fill?: string;
    fillOpacity?: number;
    fillRule?: string;
    stroke?: string;
    strokeWidth?: number;
  }>;
}

/**
 * Parse an exported individual SVG asset generated by docs/design/assets/individual/.
 * Extracts the root `translate(tx, ty)` registration offset, any remaining `<g transform>`
 * wrappers, and child `<path .../>` geometry without losing subpaths or compound fill rules.
 */
export function parseIndividualSvg(file: string, svgText: string): ParsedSvgLayer {
  const mw = /width="(\d+(?:\.\d+)?)"/.exec(svgText);
  const mh = /height="(\d+(?:\.\d+)?)"/.exec(svgText);
  const width = mw ? Number(mw[1]) : 100;
  const height = mh ? Number(mh[1]) : 100;

  const groupMatches = [...svgText.matchAll(/<g\s+transform="([^"]*)"/g)].map((g) => g[1].trim());
  let translate: [number, number] = [0, 0];
  let rootPostTransform: string | undefined;
  const innerGroupTransforms: string[] = [];

  if (groupMatches.length > 0) {
    const first = groupMatches[0];
    const tm = /^translate\(\s*([-\d.]+)\s*[,\s]\s*([-\d.]+)\s*\)(.*)$/.exec(first);
    if (tm) {
      translate = [Number(tm[1]), Number(tm[2])];
      const rem = tm[3].trim();
      if (rem) rootPostTransform = rem;
    } else if (first) {
      innerGroupTransforms.push(first);
    }
    for (let i = 1; i < groupMatches.length; i++) {
      if (groupMatches[i]) innerGroupTransforms.push(groupMatches[i]);
    }
  }

  const paths: ParsedSvgLayer["paths"] = [];
  const pathRe = /<path\s+([^>]*?)\/?>(?:<\/path>)?/g;
  let m: RegExpExecArray | null;
  while ((m = pathRe.exec(svgText)) !== null) {
    const attrs = m[1];
    const getAttr = (name: string) => {
      const r = new RegExp(`${name}="([^"]*)"`).exec(attrs);
      return r ? r[1] : undefined;
    };
    const d = getAttr("d");
    if (!d) continue;
    const tf = getAttr("transform");
    const fill = getAttr("fill");
    const fo = getAttr("fill-opacity");
    const fr = getAttr("fill-rule");
    const stroke = getAttr("stroke");
    const sw = getAttr("stroke-width");
    paths.push({
      d,
      matrixRaw: tf && /matrix\([^)]+\)/.test(tf) ? /matrix\([^)]+\)/.exec(tf)![0] : undefined,
      fill,
      fillOpacity: fo !== undefined ? Number(fo) : undefined,
      fillRule: fr,
      stroke,
      strokeWidth: sw !== undefined ? Number(sw) : undefined,
    });
  }

  return { file, width, height, translate, rootPostTransform, innerGroupTransforms, paths };
}

/**
 * Compute SVG `<g transform="...">` placing a tight-cropped individual SVG asset back into
 * its registered reference space (inverting ONLY its registered `translate(tx, ty)` and
 * preserving any post-translate root/inner group transforms recorded in the SVG).
 */
export function registeredSvgGroupTransform(
  parsed: ParsedSvgLayer,
  registration?: AssetRegistration,
  extraTransform = "",
): string {
  const [tx, ty] = registration ? registration.svgTranslate : parsed.translate;
  // Since the original SVG placed geometry at `translate(tx, ty) * rootPostTransform * innerGroupTransforms * pathTransform`,
  // translating back by `translate(-tx, -ty)` cancels `translate(tx, ty)`, yielding `rootPostTransform * innerGroupTransforms * pathTransform`
  // in exact source/reference coordinates!
  const inv = `translate(${(-tx).toFixed(4)}, ${(-ty).toFixed(4)})`;
  //Wait: translate(-tx, -ty) followed by translate(tx, ty)? No — we replace translate(tx, ty) with ZERO offset:
  // If geometry inside parsed.paths wasn't pre-multiplied by translate(tx, ty), emitting NO outer translate already places
  // `rootPostTransform * innerGroupTransforms * pathTransform` directly in reference space!
  // Let's assert parsed.translate matches registration.svgTranslate so silent mismatches never pass:
  if (
    registration &&
    (Math.abs(parsed.translate[0] - registration.svgTranslate[0]) > 0.05 ||
      Math.abs(parsed.translate[1] - registration.svgTranslate[1]) > 0.05)
  ) {
    throw new Error(
      `Asset registration mismatch for ${parsed.file}: SVG has translate(${parsed.translate.join(",")}), manifest declares (${registration.svgTranslate.join(",")})`,
    );
  }
  const chain: string[] = [];
  if (extraTransform) chain.push(extraTransform);
  if (!registration) {
    // Unannotated SVG with no registration: rely on parsed.translate inversion only as explicit fallback
    void inv;
  }
  if (parsed.rootPostTransform) chain.push(parsed.rootPostTransform);
  for (const g of parsed.innerGroupTransforms) chain.push(g);
  return chain.join(" ");
}

export function renderRegisteredSvgPaths(
  parsed: ParsedSvgLayer,
  registration: AssetRegistration | undefined,
  extraTransform = "",
  overrideFill?: string,
  overrideOpacity?: number,
): string {
  const tf = registeredSvgGroupTransform(parsed, registration, extraTransform);
  const body = parsed.paths
    .map((p) => {
      const fill = overrideFill ?? p.fill ?? "#18181b";
      const fo = overrideOpacity ?? p.fillOpacity;
      const attrs = [`d="${p.d}"`, `fill="${fill}"`];
      if (p.matrixRaw) attrs.push(`transform="${p.matrixRaw}"`);
      if (fo !== undefined && fo < 0.999) attrs.push(`fill-opacity="${fo.toFixed(3)}"`);
      if (p.fillRule) attrs.push(`fill-rule="${p.fillRule}"`);
      if (p.stroke && p.stroke !== "none") {
        attrs.push(`stroke="${p.stroke}" stroke-width="${p.strokeWidth ?? 1}"`);
      }
      return `<path ${attrs.join(" ")} />`;
    })
    .join("");
  return tf ? `<g transform="${tf}">${body}</g>` : body;
}
